static void op_add_margin(state_t *state, int which, reader_t *reader)
{
    amark_document_t *document = state->documents[which];
    amark_node_t *container = read_node(state, which, reader, PICK_CONTAINER);
    uint8_t line_byte = read_byte(reader);
    uint8_t state_byte = read_byte(reader);
    uint8_t start_byte = read_byte(reader);
    uint8_t end_byte = read_byte(reader);
    amark_margin_t margin;
    size_t count = amark_block_margin_count(container);

    margin.struct_size = sizeof margin;
    margin.line = pick_line(document, container, line_byte);
    if (line_byte == 0x80 && container != NULL)
    {
        /* The line after the last margin, or the first of the range. */
        amark_margin_t last;
        last.struct_size = sizeof last;
        if (count > 0 && amark_block_margin_at(container, count - 1, &last) == AMARK_ERROR_NONE)
        {
            margin.line = last.line + 1;
        }
    }

    margin.state = (state_byte & 0x0F) == 0x0F ? AMARK_MARGIN_LAZY
                   : (state_byte & 0x0F) == 0x0E ? (amark_margin_state_t)3
                                                  : AMARK_MARGIN_PRESENT;
    margin.flags = (state_byte & 0x10) != 0 ? AMARK_MARGIN_FIRST : 0u;
    if ((state_byte & 0x20) != 0)
    {
        margin.flags |= 0x02u;
    }
    margin.role = (uint16_t)(state_byte >> 6);
    margin.column_start = pick_column(document, margin.line, start_byte);
    margin.column_end = margin.column_start + (uint32_t)(end_byte % 5);
    if (margin.state == AMARK_MARGIN_LAZY && (end_byte & 0x80) == 0)
    {
        margin.column_end = margin.column_start;
    }

    CALL(state, amark_block_add_margin(container, &margin));
}

