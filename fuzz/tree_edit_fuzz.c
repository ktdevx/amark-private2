/*
 * The fuzz target of the editing of the syntax tree (TreeFuzz; 1.7, 14.2).
 *
 * The input is read as a sequence of operations on two documents, A and B, both
 * of the built-in syntax set. Every operation starts with a byte:
 *   bit 7     inject allocation failures; the next byte then tells how:
 *               bits 0-3  n: the number of allocations that succeed first,
 *                         n for n < 8, else 2^(n - 5) (8 to 1024), so that
 *                         the later allocations of an operation are reached;
 *               bit 4     fail only that one allocation (otherwise every later
 *                         allocation of the operation fails too);
 *   bit 6     the document to operate on (0: A, 1: B); the other one is the
 *             source or the target of the operations across documents;
 *   bits 0-5  the operation (modulo OP_COUNT), followed by its arguments,
 *             read from the input (missing bytes read as 0).
 * The operations: creating and destroying nodes; the structural edits (append,
 * prepend, insert before and after, replace, unlink); adding, appending and
 * finishing sources; recording layout (line ranges, margins, blank lines,
 * layout tokens), content (laid pieces, free content) and content tokens
 * (adding, moving, splitting); recording, setting and unsetting facets and
 * setting inline text; dropping spelling (of a facet, of a node, a margin);
 * the line operations (moving and removing lines, trimming the start of the
 * content); replacing content; copying; importing a node and the children of a
 * node; and the queries: the lookup of the definition index, the verbatim
 * judgments, the lossless verification, reading values, comparing, the
 * positions, the spelling state, the iterator, the column conversions and the
 * dump.
 *
 * The arguments are chosen to be valid often: a node is picked among the nodes
 * of the right kind (any, block, leaf with content, container, inline) in the
 * ring of its document (every node, in the tree or detached; pick_node tells
 * how), and a line, a column or a content position is picked within the range
 * of its block, the width of its line or the bytes of its content, with some
 * bytes picking raw values instead (a node of the other document, NULL, a value
 * out of range), so that the invalid arguments are exercised too. The seeds of
 * the corpus pick their nodes by their index in the ring (0xC0 + index).
 *
 * Every call of the library that the operations make is checked:
 *   - after it, the internal invariant checker (amark_tree_check) passes on both
 *     documents;
 *   - when it fails (any error) or is a query, the dumps of both documents (the
 *     document node and every detached top node, with every dump flag) are the
 *     same as before the call, and so are their counts of nodes, lines and
 *     sources: a failed operation changes nothing (1.7);
 *   - AMARK_ERROR_OUT_OF_MEMORY is returned only when an allocation failed;
 * and, at the end of the input, after both documents are destroyed, every
 * block allocated through the allocator was freed (no leak, 1.7).
 *
 * The allocator that injects the failures lives in this file (it must not come
 * from amark_test_support, which links Naos). It is set as the global allocator
 * for each input and the default allocator is restored at the end.
 *
 * The sizes are bounded (nodes, lines and sources per document, operations per
 * input), so that the checks after every call stay fast; an operation that
 * would go beyond them is skipped.
 *
 * A violated property aborts, which libFuzzer and the corpus replay report;
 * with the environment variable AMARK_TREE_EDIT_TRACE set, each call and its
 * result are written to stderr, and a violation of the checker also writes the
 * dump taken before the call.
 *
 * The corpus (corpus/tree_edit) is generated by tools/gen_tree_edit_seeds.py
 * (which mirrors the tables of this file; --check compares it with the
 * committed corpus). It holds assembled sequences: INPUT.md 3.1
 * built record by record and then queried, edited, copied and imported; link
 * reference definitions and their lookup; a fenced code block; the line
 * operations; a list with its blank line; a tab shared by a margin, a layout
 * token and the content; sources appended across a CR; free content and
 * content tokens; structural edits refused by the containment rules; a sweep
 * of injected failures; and the regressions found by replaying random inputs
 * (regression_*).
 */
