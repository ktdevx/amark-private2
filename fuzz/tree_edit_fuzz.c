/* ---- Checks -------------------------------------------------------------------- */

/* The operation being run, for the messages. */
static struct
{
    size_t index;
    unsigned code;
    const char *call;
    /* Each call and its result are written to stderr while set (the
     * environment variable AMARK_TREE_EDIT_TRACE is set), to see what an input
     * does. */
    bool trace;
} current;

static void check_failed(const char *expression, int line)
{
    fprintf(stderr,
            "tree_edit_fuzz.c:%d: property violated: %s (operation %lu, code %u, call %s)\n",
            line, expression, (unsigned long)current.index, current.code,
            current.call != NULL ? current.call : "-");
    abort();
}

#define CHECK(expression)                         \
    do {                                          \
        if (!(expression)) {                      \
            check_failed(#expression, __LINE__);  \
        }                                         \
    } while (0)

/* The bounds of a document and of an input. */
#define MAX_NODES 96
#define MAX_LINES 192
#define MAX_SOURCES 24
#define MAX_OPERATIONS 384
#define MAX_TEXT 31

#define ALL_DUMP_FLAGS \
    (AMARK_DUMP_STYLE | AMARK_DUMP_LAYOUT | AMARK_DUMP_SPELLING | AMARK_DUMP_POSITIONS | \
     AMARK_DUMP_LINES)

/* ---- The allocator that injects failures ---- */

static struct
{
    bool armed;     /* failures are injected while set */
    bool once;      /* only one allocation fails, then the injection stops */
    size_t budget;  /* the allocations that succeed before the failures */
    size_t failed;  /* the allocations refused since the last arming */
    size_t live;    /* blocks allocated and not yet freed */
} fuzz_allocator;

/* Whether the current allocation fails. */
static bool inject(void)
{
    if (!fuzz_allocator.armed)
    {
        return false;
    }

    if (fuzz_allocator.budget > 0)
    {
        fuzz_allocator.budget--;
        return false;
    }

    if (fuzz_allocator.once)
    {
        fuzz_allocator.armed = false;
    }

    fuzz_allocator.failed++;
    return true;
}

static void *fuzz_malloc(size_t size)
{
    void *block;

    if (inject())
    {
        return NULL;
    }

    block = malloc(size);
    if (block != NULL)
    {
        fuzz_allocator.live++;
    }

    return block;
}

static void *fuzz_calloc(size_t count, size_t size)
{
    void *block;

    if (inject())
    {
        return NULL;
    }

    block = calloc(count, size);
    if (block != NULL)
    {
        fuzz_allocator.live++;
    }

    return block;
}

static void *fuzz_realloc(void *ptr, size_t new_size)
{
    void *block;

    if (inject())
    {
        return NULL;
    }

    block = realloc(ptr, new_size);
    if (block != NULL && ptr == NULL)
    {
        fuzz_allocator.live++;
    }

    return block;
}

static void fuzz_free(void *ptr)
{
    CHECK(ptr != NULL);
    CHECK(fuzz_allocator.live > 0);

    fuzz_allocator.live--;
    free(ptr);
}

/* ---- The input ---- */

typedef struct
{
    const uint8_t *data;
    size_t size;
    size_t position;
} reader_t;

static uint8_t read_byte(reader_t *reader)
{
    if (reader->position >= reader->size)
    {
        return 0;
    }

    return reader->data[reader->position++];
}

/* The texts a text argument picks (bytes below 0xE0). */
static const char *const texts[] = {
    "",
    "foo",
    "Foo",
    "a b",
    "x\ny",
    "a\r\nb\rc",
    "\n",
    "a\n\n",
    "  \xc3\x9f ",
    "\xe1\xba\x9e",
    "[x]",
    "\xff\xfe",
    "a\tb",
    "http://a",
    "&amp;",
    "\\*",
    "#",
    "```",
    "- ",
    "> ",
    "    code",
    "a\n \nb",
    "one *two*",
    "bar",
};

#define TEXT_COUNT (sizeof texts / sizeof texts[0])

/* A text argument: a text of the table, NULL with a length (0xDF, invalid), or
 * up to MAX_TEXT bytes of the input (from 0xE0 on, the low 5 bits being the
 * length). buffer holds at least MAX_TEXT bytes. */
static const char *read_text(reader_t *reader, char *buffer, size_t *length)
{
    uint8_t selector = read_byte(reader);
    size_t i;

    if (selector < 0xDF)
    {
        const char *text = texts[selector % TEXT_COUNT];
        *length = strlen(text);
        return text;
    }

    if (selector == 0xDF)
    {
        *length = 1;
        return NULL;
    }

    *length = (size_t)(selector & 0x1F);
    for (i = 0; i < *length; i++)
    {
        buffer[i] = (char)read_byte(reader);
    }

    return buffer;
}

/* The sources an added source picks (bytes below 0xE0). */
static const char *const sources[] = {
    "> - one *two\n>   three* four\n",
    "# a #\n",
    "```\nx\n```\n",
    "p1\np2\n",
    ">\t\tfoo\n",
    "a\r\nb\rc",
    "",
    "\357\273\277bom\n",
    "[foo]: /url \"t\"\n",
    "x",
    "  \n\n",
    "[t][Foo] [foo]\n",
    "- a\n\n- b\n",
    "> a\nb\n",
};

#define SOURCE_COUNT (sizeof sources / sizeof sources[0])

/* The numbers a number argument picks (bytes below 0xF0); from 0xF0 on, the
 * low 4 bits. */
static const int64_t numbers[] = {
    0, 1, 2, 3, 4, 5, 6, 7, -1, 9, 10, 999999999, 1000000000, INT64_MAX, INT64_MIN,
};

#define NUMBER_COUNT (sizeof numbers / sizeof numbers[0])

static int64_t read_number(reader_t *reader)
{
    uint8_t selector = read_byte(reader);

    if (selector >= 0xF0)
    {
        return (int64_t)(selector & 0x0F);
    }

    return numbers[selector % NUMBER_COUNT];
}

/* ---- The state ---- */

typedef struct
{
    amark_document_t *documents[2];
    /* The snapshots before and after a call. */
    amark_buffer_t before[2];
    amark_buffer_t after[2];
    size_t counts[2][3];
    /* The failure injection of the current operation. */
    bool inject;
    bool inject_once;
    size_t inject_budget;
    /* A scratch buffer for the dump query. */
    amark_buffer_t scratch;
} state_t;

/* Dumps document: its document node, then each detached top node of its ring,
 * in the order of the ring. */
static void snapshot_document(amark_document_t *document, amark_buffer_t *out)
{
    amark_node_t *root = amark_document_root(document);
    amark_node_t *node;

    amark_buffer_clear(out);
    CHECK(amark_node_dump(root, ALL_DUMP_FLAGS, out) == AMARK_ERROR_NONE);
    for (node = root->ring_next; node != root; node = node->ring_next)
    {
        if (node->parent == NULL)
        {
            CHECK(amark_buffer_append_cstr(out, "--\n") == AMARK_ERROR_NONE);
            CHECK(amark_node_dump(node, ALL_DUMP_FLAGS, out) == AMARK_ERROR_NONE);
        }
    }
}

static void count_document(const amark_document_t *document, size_t counts[3])
{
    counts[0] = document->node_count;
    counts[1] = amark_document_line_count(document);
    counts[2] = amark_document_source_count(document);
}

static void check_documents(state_t *state)
{
    int i;

    for (i = 0; i < 2; i++)
    {
        amark_tree_check_report_t report;
        amark_tree_violation_t violation = amark_tree_check(state->documents[i], &report);

        if (violation != AMARK_TREE_VIOLATION_NONE)
        {
            fprintf(stderr, "tree_edit_fuzz: document %c: violation %s: %s\n", 'A' + i,
                    amark_tree_violation_name(violation),
                    report.message != NULL ? report.message : "-");
            if (current.call != NULL)
            {
                fprintf(stderr, "--- before the call\n%s", amark_buffer_data(&state->before[i]));
            }
        }

        CHECK(violation == AMARK_TREE_VIOLATION_NONE);
    }
}

/* Before a call: takes the snapshots and arms the failure injection. */
static void call_begin(state_t *state, const char *name)
{
    int i;

    current.call = name;
    for (i = 0; i < 2; i++)
    {
        snapshot_document(state->documents[i], &state->before[i]);
        count_document(state->documents[i], state->counts[i]);
    }

    fuzz_allocator.failed = 0;
    fuzz_allocator.budget = state->inject_budget;
    fuzz_allocator.once = state->inject_once;
    fuzz_allocator.armed = state->inject;
}

/* After a call that returned error: disarms the injection and checks the
 * documents; a failed call and a query must have changed nothing. */
static void call_end(state_t *state, amark_error_t error, bool query)
{
    int i;

    fuzz_allocator.armed = false;

    if (current.trace)
    {
        fprintf(stderr, "%3lu %-58.58s %d%s\n", (unsigned long)current.index, current.call,
                (int)error, fuzz_allocator.failed > 0 ? " (failures injected)" : "");
    }

    CHECK((int)error >= 0 && (int)error <= (int)AMARK_ERROR_NOT_LOSSLESS);
    if (error == AMARK_ERROR_OUT_OF_MEMORY)
    {
        CHECK(fuzz_allocator.failed > 0);
    }

    check_documents(state);

    if (error == AMARK_ERROR_NONE && !query)
    {
        return;
    }

    for (i = 0; i < 2; i++)
    {
        size_t counts[3];

        snapshot_document(state->documents[i], &state->after[i]);
        count_document(state->documents[i], counts);
        if (amark_buffer_length(&state->before[i]) != amark_buffer_length(&state->after[i]) ||
            memcmp(amark_buffer_data(&state->before[i]), amark_buffer_data(&state->after[i]),
                   amark_buffer_length(&state->before[i])) != 0)
        {
            fprintf(stderr, "tree_edit_fuzz: document %c changed (error %d):\n--- before\n%s"
                            "--- after\n%s",
                    'A' + i, (int)error, amark_buffer_data(&state->before[i]),
                    amark_buffer_data(&state->after[i]));
            CHECK(!"the dump is the same as before the call");
        }

        CHECK(counts[0] == state->counts[i][0]);
        CHECK(counts[1] == state->counts[i][1]);
        CHECK(counts[2] == state->counts[i][2]);
    }
}

#define CALL(state, expression)                                \
    do {                                                       \
        amark_error_t call_error_;                             \
        call_begin((state), #expression);                      \
        call_error_ = (expression);                            \
        call_end((state), call_error_, false);                 \
    } while (0)

#define QUERY(state, expression)                               \
    do {                                                       \
        amark_error_t call_error_;                             \
        call_begin((state), #expression);                      \
        call_error_ = (expression);                            \
        call_end((state), call_error_, true);                  \
    } while (0)

/* ---- Picking the arguments ---- */

typedef enum
{
    PICK_ANY,
    PICK_BLOCK,
    PICK_LEAF,
    PICK_CONTAINER,
    PICK_INLINE,
    PICK_PARENT
} pick_kind_t;

static bool pick_matches(const amark_node_t *node, pick_kind_t kind)
{
    switch (kind)
    {
    case PICK_BLOCK:
        return amark_node_is_block(node);
    case PICK_LEAF:
        return amark_node_has_content(node);
    case PICK_CONTAINER:
        return amark_node_is_container(node);
    case PICK_INLINE:
        return amark_node_is_inline(node);
    case PICK_PARENT:
        return amark_node_can_contain(node, AMARK_NODE_TEXT) ||
               amark_node_can_contain(node, AMARK_NODE_PARAGRAPH) ||
               amark_node_can_contain(node, AMARK_NODE_ITEM);
    case PICK_ANY:
    default:
        return true;
    }
}

/* Picks a node of document, in the order of its ring (the document node first,
 * then the other nodes in the order of their creation):
 *   - below 0xC0, the node of kind (any node when there is none of kind) at the
 *     byte modulo their count;
 *   - 0xC0-0xEF, the node at the byte - 0xC0 modulo the count of the nodes;
 *   - 0xF0-0xFE, the node of the other document at the low 4 bits modulo the
 *     count of its nodes;
 *   - 0xFF, NULL. */
static amark_node_t *pick_node(state_t *state, int which, uint8_t selector, pick_kind_t kind)
{
    amark_document_t *document = state->documents[which];
    amark_node_t *root = amark_document_root(document);
    amark_node_t *node;
    size_t count = 0;
    size_t index;

    if (selector == 0xFF)
    {
        return NULL;
    }

    if (selector >= 0xF0)
    {
        document = state->documents[1 - which];
        root = amark_document_root(document);
        kind = PICK_ANY;
        selector = (uint8_t)(selector & 0x0F);
    }
    else if (selector >= 0xC0)
    {
        kind = PICK_ANY;
        selector = (uint8_t)(selector - 0xC0);
    }

    node = root;
    do
    {
        if (pick_matches(node, kind))
        {
            count++;
        }
        node = node->ring_next;
    } while (node != root);

    if (count == 0)
    {
        kind = PICK_ANY;
        count = document->node_count;
    }

    index = selector % count;
    node = root;
    for (;;)
    {
        if (pick_matches(node, kind))
        {
            if (index == 0)
            {
                return node;
            }
            index--;
        }
        node = node->ring_next;
    }
}

static amark_node_t *read_node(state_t *state, int which, reader_t *reader, pick_kind_t kind)
{
    return pick_node(state, which, read_byte(reader), kind);
}

/* The nearest block among node and its ancestors (NULL when none). */
static amark_node_t *leaf_of(amark_node_t *node)
{
    while (node != NULL && !amark_node_is_block(node))
    {
        node = node->parent;
    }

    return node;
}

/* The width of line (0 when there is none). */
static uint32_t line_width(const amark_document_t *document, amark_line_id_t line)
{
    amark_line_info_t info;

    info.struct_size = sizeof info;
    if (amark_document_line(document, line, &info) != AMARK_ERROR_NONE)
    {
        return 0;
    }

    return info.width;
}

/* Picks a line for block: from 0x80 on, within the range of block (the byte
 * modulo its count), else any line of the table or the one after it. */
static amark_line_id_t pick_line(const amark_document_t *document, const amark_node_t *block,
                                 uint8_t selector)
{
    amark_line_id_t first = AMARK_LINE_NONE;
    uint32_t count = 0;

    if ((selector & 0x80) != 0 && block != NULL &&
        amark_block_lines(block, &first, &count) == AMARK_ERROR_NONE && count > 0)
    {
        return first + (amark_line_id_t)((selector & 0x7F) % count);
    }

    return (amark_line_id_t)((selector & 0x7F) % (amark_document_line_count(document) + 1));
}

/* A column of line: the byte modulo the width + 2 (one past the end is
 * invalid). */
static uint32_t pick_column(const amark_document_t *document, amark_line_id_t line,
                            uint8_t selector)
{
    return (uint32_t)(selector % ((size_t)line_width(document, line) + 2));
}

/* A facet of node: the byte modulo its facet count + 2 (0 and the one after the
 * last are invalid). */
static amark_facet_t pick_facet(const amark_node_t *node, uint8_t selector)
{
    const amark_node_type_desc_t *desc = amark_node_type_desc(node);
    size_t count = desc != NULL ? desc->facet_count : 0;

    return (amark_facet_t)(selector % (count + 2));
}

static amark_spell_kind_t pick_kind(uint8_t selector)
{
    /* Mostly TEXT; 0 and 10 are invalid. */
    if (selector < 0x80)
    {
        return AMARK_SPELL_TEXT;
    }

    return (amark_spell_kind_t)(selector % 11);
}

/* The number of nodes of the subtree of node. */
static size_t subtree_size(const amark_node_t *node)
{
    const amark_node_t *current_node = node;
    size_t count = 0;

    if (node == NULL)
    {
        return 0;
    }

    for (;;)
    {
        count++;
        if (current_node->first_child != NULL)
        {
            current_node = current_node->first_child;
            continue;
        }

        while (current_node != node && current_node->next == NULL)
        {
            current_node = current_node->parent;
        }

        if (current_node == node)
        {
            return count;
        }

        current_node = current_node->next;
    }
}

/* Whether document can get extra more nodes. */
static bool room(const state_t *state, int which, size_t extra)
{
    return state->documents[which]->node_count + extra <= MAX_NODES;
}

static bool line_room(const state_t *state, int which)
{
    return amark_document_line_count(state->documents[which]) < MAX_LINES &&
           amark_document_source_count(state->documents[which]) < MAX_SOURCES;
}

/* ---- The operations ---- */

typedef void (*operation_t)(state_t *state, int which, reader_t *reader);

static void op_create(state_t *state, int which, reader_t *reader)
{
    amark_node_t *node = NULL;
    amark_node_type_t type = (amark_node_type_t)(read_byte(reader) % 21);

    if (!room(state, which, 1))
    {
        return;
    }

    CALL(state, amark_node_create(state->documents[which], type, &node));
}

static void op_append_child(state_t *state, int which, reader_t *reader)
{
    amark_node_t *parent = read_node(state, which, reader, PICK_PARENT);
    amark_node_t *node = read_node(state, which, reader, PICK_ANY);

    CALL(state, amark_node_append_child(parent, node));
}

static void op_prepend_child(state_t *state, int which, reader_t *reader)
{
    amark_node_t *parent = read_node(state, which, reader, PICK_PARENT);
    amark_node_t *node = read_node(state, which, reader, PICK_ANY);

    CALL(state, amark_node_prepend_child(parent, node));
}

static void op_insert_before(state_t *state, int which, reader_t *reader)
{
    amark_node_t *anchor = read_node(state, which, reader, PICK_ANY);
    amark_node_t *node = read_node(state, which, reader, PICK_ANY);

    CALL(state, amark_node_insert_before(anchor, node));
}

static void op_insert_after(state_t *state, int which, reader_t *reader)
{
    amark_node_t *anchor = read_node(state, which, reader, PICK_ANY);
    amark_node_t *node = read_node(state, which, reader, PICK_ANY);

    CALL(state, amark_node_insert_after(anchor, node));
}

static void op_replace(state_t *state, int which, reader_t *reader)
{
    amark_node_t *old_node = read_node(state, which, reader, PICK_ANY);
    amark_node_t *new_node = read_node(state, which, reader, PICK_ANY);

    CALL(state, amark_node_replace(old_node, new_node));
}

static void op_unlink(state_t *state, int which, reader_t *reader)
{
    amark_node_t *node = read_node(state, which, reader, PICK_ANY);

    CALL(state, amark_node_unlink(node));
}

static void op_destroy(state_t *state, int which, reader_t *reader)
{
    amark_node_t *node = read_node(state, which, reader, PICK_ANY);

    /* Cannot fail: the call is checked as a successful one. */
    call_begin(state, "amark_node_destroy");
    amark_node_destroy(node);
    call_end(state, AMARK_ERROR_NONE, false);
}

static void op_add_source(state_t *state, int which, reader_t *reader)
{
    uint8_t selector = read_byte(reader);
    uint8_t flags_byte;
    char buffer[MAX_TEXT];
    const char *bytes;
    size_t length;
    uint32_t flags;
    amark_source_id_t source = 0;

    if (!line_room(state, which))
    {
        return;
    }

    if (selector < 0xE0)
    {
        bytes = sources[selector % SOURCE_COUNT];
        length = strlen(bytes);
    }
    else
    {
        /* The selector is the one of a text of the input. */
        reader->position--;
        bytes = read_text(reader, buffer, &length);
    }

    flags_byte = read_byte(reader);

    /* Mostly finished; 0x02 is an invalid flag. */
    flags = (flags_byte & 0x80) != 0 ? 0u : AMARK_SOURCE_FINISHED;
    if (flags_byte == 0x7F)
    {
        flags = 0x02u;
    }

    CALL(state, amark_document_add_source(state->documents[which], bytes, length, flags,
                                          &source));
}

static void op_append_source(state_t *state, int which, reader_t *reader)
{
    amark_source_id_t source = (amark_source_id_t)read_byte(reader);
    char buffer[MAX_TEXT];
    const char *bytes;
    size_t length;
    size_t count = amark_document_source_count(state->documents[which]);

    bytes = read_text(reader, buffer, &length);
    if (!line_room(state, which))
    {
        return;
    }

    if (count > 0 && source < 0xF0)
    {
        source = (amark_source_id_t)(source % count);
    }

    CALL(state, amark_document_append_source(state->documents[which], source, bytes, length));
}

static void op_finish_source(state_t *state, int which, reader_t *reader)
{
    amark_source_id_t source = (amark_source_id_t)read_byte(reader);
    size_t count = amark_document_source_count(state->documents[which]);

    if (count > 0 && source < 0xF0)
    {
        source = (amark_source_id_t)(source % count);
    }

    CALL(state, amark_document_finish_source(state->documents[which], source));
}

