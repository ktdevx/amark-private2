/* The lines of an operation on the lines of leaf: from 0x80 on, the first
 * (bit 6 clear) or the last lines of its range, else any. */
static void pick_lines(const state_t *state, int which, const amark_node_t *leaf,
                       uint8_t selector, amark_line_id_t *first, uint32_t *count)
{
    amark_line_id_t range_first = AMARK_LINE_NONE;
    uint32_t range_count = 0;
    uint32_t n = (uint32_t)(selector & 0x07) + 1;

    if ((selector & 0x80) != 0 && leaf != NULL &&
        amark_block_lines(leaf, &range_first, &range_count) == AMARK_ERROR_NONE &&
        range_count > 0)
    {
        if (n > range_count)
        {
            n = range_count;
        }
        *count = n;
        *first = (selector & 0x40) == 0 ? range_first : range_first + range_count - n;
        return;
    }

    *first = (amark_line_id_t)((selector >> 3) %
                               (amark_document_line_count(state->documents[which]) + 1));
    *count = n - 1;
}

