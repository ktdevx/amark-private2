int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
    static const amark_allocator_t allocator = {fuzz_malloc, fuzz_calloc, fuzz_realloc,
                                                fuzz_free};
    reader_t reader;
    state_t state;
    int i;

    reader.data = data;
    reader.size = size;
    reader.position = 0;

    memset(&fuzz_allocator, 0, sizeof fuzz_allocator);
    current.index = 0;
    current.code = 0;
    current.call = NULL;
#if defined(_MSC_VER)
#pragma warning(push)
#pragma warning(disable : 4996) /* getenv: only reads whether a variable is set */
#endif
    current.trace = getenv("AMARK_TREE_EDIT_TRACE") != NULL;
#if defined(_MSC_VER)
#pragma warning(pop)
#endif
    CHECK(amark_allocator_set(&allocator) == AMARK_ERROR_NONE);

    memset(&state, 0, sizeof state);
    for (i = 0; i < 2; i++)
    {
        CHECK(amark_document_create(NULL, &state.documents[i]) == AMARK_ERROR_NONE);
        amark_buffer_init(&state.before[i]);
        amark_buffer_init(&state.after[i]);
    }
    amark_buffer_init(&state.scratch);
    check_documents(&state);

    while (reader.position < reader.size && current.index < MAX_OPERATIONS)
    {
        uint8_t code = read_byte(&reader);
        int which = (code & 0x40) != 0 ? 1 : 0;

        state.inject = (code & 0x80) != 0;
        state.inject_once = false;
        state.inject_budget = 0;
        if (state.inject)
        {
            uint8_t how = read_byte(&reader);
            size_t n = (size_t)(how & 0x0F);

            state.inject_budget = n < 8 ? n : (size_t)1 << (n - 5);
            state.inject_once = (how & 0x10) != 0;
        }

        current.code = (unsigned)((code & 0x3F) % OP_COUNT);
        current.call = NULL;
        operations[current.code](&state, which, &reader);
        current.index++;
    }

    for (i = 0; i < 2; i++)
    {
        amark_document_destroy(state.documents[i]);
        amark_buffer_deinit(&state.before[i]);
        amark_buffer_deinit(&state.after[i]);
    }
    amark_buffer_deinit(&state.scratch);

    /* Every block allocated through the allocator was freed. */
    CHECK(fuzz_allocator.live == 0);
    CHECK(amark_allocator_set(NULL) == AMARK_ERROR_NONE);

    return 0;
}
